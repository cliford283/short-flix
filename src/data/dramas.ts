function generateEpisodes(count: number, freeCount: number, coinPrice: number = 28) {
  return Array.from({ length: count }, (_, i) => {
    const epNum = i + 1;
    const isFree = epNum <= freeCount;
    return {
      id: epNum,
      number: epNum,
      title: `Episode ${epNum}: ${getEpisodeTitle(epNum)}`,
      duration: '1:45',
      isFree,
      coinPrice: isFree ? 0 : coinPrice,
      isUnlocked: isFree,
      synopsis: getEpisodeSynopsis(epNum),
    };
  });
}

function getEpisodeTitle(num: number): string {
  const titles = [
    'The Sudden Crash',
    'Whispers in the Rain',
    'The Hidden Contract',
    'Dangerous Truths',
    'A Shadow Behind',
    'Midnight Confession',
    'Betrayal Revealed',
    'The Final Trap',
    'Breaking Free',
    'The Secret Conspiracy',
    'Second Chances',
    'Twist of Fate',
    'Unmasked',
    'Point of No Return',
    'Crossfire',
  ];
  return titles[(num - 1) % titles.length] || `Chapter ${num}`;
}

function getEpisodeSynopsis(num: number): string {
  const snips = [
    'Vagabond is a 2019 South Korean action thriller television series broadcast on SBS and globally distributed by Netflix. Stuntman Cha Dal-gun gets entangled in a devastating plane crash investigation, uncovering a terrifying web of national corruption.',
    'An encounter in the rainy alley forces an unexpected alliance with NIS agent Go Hae-ri.',
    'Tensions rise as secret documents are leaked to the rival syndicate in Seoul.',
    'A high-stakes chase through the neon alleys of Seoul tests loyalty to the limit.',
    'A shocking truth emerges about who was pulling the strings from the shadows.',
  ];
  return snips[(num - 1) % snips.length];
}

